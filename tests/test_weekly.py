def colour(image_b64: str) -> str:
    png = base64.b64decode(image_b64)
    data, i = b"", 8
    while i < len(png):
        length = int.from_bytes(png[i:i + 4], "big")
        if png[i + 4:i + 8] == b"IDAT":
            data += png[i + 8:i + 8 + length]
        i += 12 + length
    r, g, b = zlib.decompress(data)[1:4]
    return "red" if r > 200 and g < 100 else "blue" if b > 200 else "green" if g > 150 and r < 100 else "yellow"


class Handler(BaseHTTPRequestHandler):
    def log_message(self, *a):
        pass

    def reply(self, code, body):
        data = json.dumps(body).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def known(self, model):
        created = json.loads((fake / "ollama_models.json").read_text()) if (fake / "ollama_models.json").exists() else {}
        return model.split(":latest")[0] in created or model == "gemma4:e4b"

    def do_GET(self):
        if self.path == "/api/ps":
            size = 3_200_000_000
            return self.reply(200, {"models": [{"name": m if ":" in m else m + ":latest", "size": size,
                                                "size_vram": size if server["fit"] else size // 2}
                                               for m in server["loaded"][-2:]]})
        self.reply(404, {"error": "no"})

    def do_POST(self):
        body = json.loads(self.rfile.read(int(self.headers["Content-Length"])))
        if self.path == "/api/show":
            if body["model"] != "gemma4:e4b":
                return self.reply(404, {"error": f"model '{body['model']}' not found"})
            return self.reply(200, {"modelfile": STOCK_MODELFILE})
        model = body["model"]
        if not self.known(model):
            return self.reply(404, {"error": f"model '{model}' not found"})
        server["requests"].append(body)
        server["loaded"] = [m for m in server["loaded"] if m != model] + [model]
        assert body["options"]["num_ctx"] == 8192 and body["think"] is False
        images = [img for m in body["messages"] for img in m.get("images", [])]
        if images:
            if model.startswith("gomi-w") and model not in server["sees"]:
                return self.reply(400, {"error": "model does not support images"})
            return self.reply(200, {"message": {"content": colour(images[0]).capitalize()}})
        props = (body.get("format") or {}).get("properties", {})
        if "interest" in props:
            content = json.dumps({"read": "kaz0 venting about the patch", "interest": 4,
                                  "emoji": props["emoji"]["enum"][0]})
        elif "recap" in props:
            content = json.dumps({"recap": "norimaki got a bakery job and sleepyfox started guitar.",
                                  "notes": [{"who": "norimaki", "note": "norimaki starts a bakery job",
                                             "quote": "new job at the bakery"}]})
        else:
            content = f"<think>hmm</think>[{model}] says hi to {body['messages'][-1]['content'][-12:]!r}"
        self.reply(200, {"message": {"content": content}})


